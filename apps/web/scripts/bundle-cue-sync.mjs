// Builds the single-file version of the cue-sync function.
//
// The deployed functions on this project are single files (see time-tracker-sync), so a
// relative import of ../_shared/cue-sync-core.ts cannot be used there. This joins the
// receiver's core logic and the database wiring into one index.ts.
//
//   node scripts/bundle-cue-sync.mjs           write supabase/functions-bundled/cue-sync/index.ts
//   node scripts/bundle-cue-sync.mjs --check   fail if the written file is out of date
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "supabase");
const OUT = join(root, "functions-bundled", "cue-sync", "index.ts");

const CORE_IMPORT = /^import \{[^}]*\} from "\.\.\/_shared\/cue-sync-core\.ts";\n/gm;
const CORE_TYPE_IMPORT = /^import type \{[^}]*\} from "\.\.\/_shared\/cue-sync-core\.ts";\n/gm;

export function buildBundle() {
  const core = readFileSync(join(root, "functions", "_shared", "cue-sync-core.ts"), "utf8");
  const entry = readFileSync(join(root, "functions", "cue-sync", "index.ts"), "utf8");
  if (!CORE_IMPORT.test(entry) || !CORE_TYPE_IMPORT.test(entry)) {
    throw new Error("cue-sync/index.ts no longer imports the core the way this bundler expects");
  }
  CORE_IMPORT.lastIndex = 0;
  CORE_TYPE_IMPORT.lastIndex = 0;
  const body = entry.replace(CORE_IMPORT, "").replace(CORE_TYPE_IMPORT, "");
  // Keep the entry's leading comment and its remaining imports at the top, then the core, then the wiring.
  const firstCode = body.search(/^import /m);
  const header = body.slice(0, firstCode);
  const rest = body.slice(firstCode);
  const importEnd = rest.search(/^(?!import )/m);
  const imports = rest.slice(0, importEnd);
  const wiring = rest.slice(importEnd);
  return (
    "// GENERATED by scripts/bundle-cue-sync.mjs from functions/_shared/cue-sync-core.ts and\n" +
    "// functions/cue-sync/index.ts. Do not edit this file; edit those and run `pnpm run bundle:functions`.\n" +
    "// Deploy it as the single file of the cue-sync function.\n\n" +
    header +
    imports +
    "\n// ── cue-sync-core.ts ────────────────────────────────────────────────────────\n" +
    core.trimEnd() +
    "\n\n// ── cue-sync/index.ts ───────────────────────────────────────────────────────\n" +
    wiring.replace(/^\n+/, "")
  );
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = buildBundle();
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(OUT, "utf8"); } catch { /* missing counts as out of date */ }
    if (current !== text) {
      console.error("supabase/functions-bundled/cue-sync/index.ts is out of date; run: pnpm run bundle:functions");
      process.exit(1);
    }
    console.log("cue-sync bundle is up to date");
  } else {
    mkdirSync(dirname(OUT), { recursive: true });
    writeFileSync(OUT, text);
    console.log("wrote", OUT);
  }
}
